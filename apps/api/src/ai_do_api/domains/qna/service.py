def mark_document_indexed(db: Session, *, resource_id: str, chunk_count: int) -> None:
    doc = db.get(QnaDocument, resource_id)
    if doc is None:
        return
    doc.rag_status = "indexed"
    doc.chunk_count = chunk_count
    doc.last_error = None
    doc.indexed_at = utcnow_naive()
    db.add(doc)


def mark_document_failed(db: Session, *, resource_id: str, error: str, phase: str) -> None:
    doc = db.get(QnaDocument, resource_id)
    if doc is None:
        return
    doc.rag_status = "failed"
    doc.last_error = f"[{phase}] {error}"[:2000]
    db.add(doc)
