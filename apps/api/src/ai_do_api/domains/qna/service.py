async def stream_question_answer(
    db: Session,
    *,
    user: User,
    question: str,
    top_k: int = 20,
    conversation_id: str | None = None,
) -> AsyncIterator[QnaAnswerStreamEvent]:
    search_response = search_question_evidence(
        db,
        user=user,
        question=question,
        top_k=top_k,
        conversation_id=conversation_id,
    )
    response = _as_qna_grounded_response(search_response)
    url_answer = build_qna_url_lookup_answer(query=question, hits=response.hits)
    if url_answer is not None:
        yield QnaAnswerDelta(url_answer.text)
        yield QnaAnswerCompleted(
            _with_qna_answer(
                response,
                url_answer,
                query_profile_flag="qna_url_lookup_answer",
            )
        )
        return

    if not response.hits:
        yield QnaAnswerCompleted(response)
        return

    gateway_workspace_id = rag_application.resolve_ai_gateway_workspace_id(db, user)
    if gateway_workspace_id is None:
        raise QnaAnswerGenerationError("No active workspace is available for answer generation.")

    messages = DEFAULT_GROUNDED_ANSWER_ASSEMBLER.build_stream_messages(
        query=question,
        hits=response.hits,
    )
    chunks: list[str] = []
    finish_reason: str | None = None
    async for chunk, _decision, _config in stream_llm(
        "rag_grounded_answer",
        LlmWorkloadContext(
            workspace_id=gateway_workspace_id,
            source="api.qna.ask.stream",
            actor_user_id=user.id,
            app_id="rag",
            principal_kind="user",
            principal_id=user.id,
        ),
        db,
        messages=messages,
        stream_reasoning=False,
        context_pack=AiGatewayContextPack(
            messages=messages,
            context_strategy="rag_grounded_answer_stream_evidence",
            source_kinds=tuple(
                sorted({hit.source_kind for hit in response.hits if hit.source_kind})
            ),
            sensitivity_labels=("internal",),
            content_origin="internal_context",
        ),
        temperature=0,
        reasoning_effort="none",
        conversation_id=conversation_id,
    ):
        if chunk.kind == "content" and chunk.text:
            chunks.append(chunk.text)
            yield QnaAnswerDelta(chunk.text)
        elif chunk.kind == "done":
            finish_reason = chunk.finish_reason or "stop"

    if finish_reason not in (None, "stop"):
        raise QnaAnswerGenerationError(f"Q&A stream did not finish cleanly: {finish_reason}")

    answer_text = "".join(chunks).strip()
    if not answer_text:
        raise QnaAnswerGenerationError("Q&A stream returned an empty answer.")

    citations = _qna_citations_from_hits(response.hits)
    answer = RagGroundedAnswer(
        text=answer_text,
        citations=citations,
        unsupported_claims=[],
        sources_used=sorted({citation.source_kind for citation in citations}),
    )
    yield QnaAnswerCompleted(
        _with_qna_answer(
            response,
            answer,
            query_profile_flag="qna_streamed_answer",
        )
    )


def trigger_board_sync() -> None:
    dispatch_board_sync()


