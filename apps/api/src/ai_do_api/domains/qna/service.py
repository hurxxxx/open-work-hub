def _read_first_qna_object(storage_keys: list[str | None]) -> bytes | None:
    for storage_key in storage_keys:
        if not storage_key:
            continue
        try:
            return read_qna_object(storage_key)
        except Exception:
            continue
    return None


def list_documents(db: Session, *, kind: str | None = None) -> list[QnaDocument]:
    stmt = select(QnaDocument).where(QnaDocument.scope_kind == QNA_SCOPE_KIND)
    if kind is not None:
        stmt = stmt.where(QnaDocument.kind == kind)
    stmt = stmt.order_by(QnaDocument.created_at.desc())
    return list(db.scalars(stmt))


