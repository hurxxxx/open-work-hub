def _checksum(*parts: object) -> str:
    digest = hashlib.sha256()
    for part in parts:
        digest.update(str(part or "").encode("utf-8"))
        digest.update(b"\x00")
    return digest.hexdigest()


def _truncate(text: str) -> str:
    text = text or ""
    if len(text) > QNA_MAX_BODY_CHARS:
        return text[:QNA_MAX_BODY_CHARS] + "\n[이하 생략]"
    return text


def normalize_attachment_name(filename: str) -> str:
    """Return a display/storage filename, not a groupware path fragment."""
    normalized = (filename or "").replace("\\", "/").strip()
    normalized = normalized.split("?", 1)[0].split("#", 1)[0].strip().strip("/")
    normalized = normalized.rsplit("/", 1)[-1].strip()
    normalized = _ATTACHMENT_CONTROL_CHARS_RE.sub(" ", normalized).strip()
    return normalized or "attachment"


def normalize_attachment_names(filenames: list[str] | None) -> list[str]:
    seen: set[str] = set()
    normalized: list[str] = []
    for raw_name in filenames or []:
        name = normalize_attachment_name(str(raw_name))
        if name in seen:
            continue
        seen.add(name)
        normalized.append(name)
    return normalized


def _meaningful_query_terms(query: str) -> list[str]:
    terms: list[str] = []
    seen: set[str] = set()
    for match in _QUERY_TOKEN_RE.finditer(query.lower()):
        token = match.group(0).strip()
        if len(token) < 2 or token in _QUERY_STOP_WORDS or token in seen:
            continue
        seen.add(token)
        terms.append(token)
    return terms


def _is_url_lookup_query(query: str) -> bool:
    return bool(_URL_LOOKUP_QUERY_RE.search(query or ""))


def _hit_lookup_text(hit: RagQueryHit) -> str:
    return "\n".join(
        part for part in [hit.title or "", hit.summary or "", hit.excerpt or ""] if part
    )


def _cleanup_url(raw_url: str) -> str:
    return raw_url.rstrip(".,;:)]}>\"'")


def _cleanup_url_label(raw_label: str, *, fallback: str) -> str:
    label = re.sub(r"^[\s\-–—•※·\d.)]+", "", raw_label or "").strip()
    label = re.sub(r"\bURL\b", "", label, flags=re.IGNORECASE)
    label = re.sub(r"\s+", " ", label).strip(" :-：")
    return label or fallback


def _label_for_url(*, before: str, hit: RagQueryHit, terms: list[str]) -> str:
    tail = before[-100:]
    label_match = re.search(
        r"([A-Za-z0-9가-힣+#&·\s()_-]{2,40})\s*(?:URL|주소)?\s*[:：]\s*$",
        tail,
        flags=re.IGNORECASE,
    )
    fallback = terms[0] if terms else hit.title or "관련 링크"
    if label_match:
        return _cleanup_url_label(label_match.group(1), fallback=fallback)
    for term in terms:
        if term in tail.lower():
            return _cleanup_url_label(term, fallback=fallback)
    return _cleanup_url_label(hit.title or fallback, fallback=fallback)


def _url_mentions_for_hit(hit: RagQueryHit, *, terms: list[str]) -> list[_UrlMention]:
    text = _hit_lookup_text(hit)
    if not text:
        return []
    mentions: list[_UrlMention] = []
    for match in _URL_RE.finditer(text):
        url = _cleanup_url(match.group(0))
        start, end = match.span()
        before = text[max(0, start - 140) : start]
        after = text[end : min(len(text), end + 80)]
        context = f"{before}{url}{after}"
        label = _label_for_url(before=before, hit=hit, terms=terms)
        label_lower = label.lower()
        url_lower = url.lower()
        if terms and not any(term in label_lower or term in url_lower for term in terms):
            continue
        mentions.append(
            _UrlMention(
                label=label,
                url=url,
                hit=hit,
                quote=" ".join(context.split()),
            )
        )
    return mentions


def build_qna_url_lookup_answer(
    *,
    query: str,
    hits: list[RagQueryHit],
) -> RagGroundedAnswer | None:
    if not _is_url_lookup_query(query):
        return None
    terms = _meaningful_query_terms(query)
    mentions: list[_UrlMention] = []
    seen_urls: set[str] = set()
    for hit in hits:
        for mention in _url_mentions_for_hit(hit, terms=terms):
            if mention.url in seen_urls:
                continue
            seen_urls.add(mention.url)
            mentions.append(mention)
    if not mentions:
        return None

    if len(mentions) == 1:
        text = f"{mentions[0].label} 주소는 {mentions[0].url} 입니다."
    else:
        subject = terms[0] if terms else "관련"
        text = "\n".join(
            [
                f"{subject} 관련 주소는 다음과 같습니다.",
                *[f"- {mention.label}: {mention.url}" for mention in mentions[:5]],
            ]
        )

    citations = [
        RagGroundedCitation(
            resource_id=mention.hit.resource_id,
            source_kind=mention.hit.source_kind,
            quote=mention.quote,
            locator=mention.hit.citation,
        )
        for mention in mentions[:5]
    ]
    return RagGroundedAnswer(
        text=text,
        citations=citations,
        unsupported_claims=[],
        sources_used=sorted({citation.source_kind for citation in citations}),
    )


def _with_qna_answer(
    response: RagQueryResponse,
    answer: RagGroundedAnswer,
    *,
    query_profile_flag: str,
) -> RagQueryResponse:
    return response.model_copy(
        update={
            "grounded_answer": answer,
            "sources_used": answer.sources_used,
            "query_profile": {
                **response.query_profile,
                query_profile_flag: True,
            },
        }
    )


def _as_qna_grounded_response(response: RagQueryResponse) -> RagQueryResponse:
    if response.answer_mode == RagAnswerMode.GROUNDED_ANSWER:
        return response
    return response.model_copy(update={"answer_mode": RagAnswerMode.GROUNDED_ANSWER})


def _qna_citations_from_hits(hits: list[RagQueryHit]) -> list[RagGroundedCitation]:
    citations: list[RagGroundedCitation] = []
    seen: set[tuple[str, str | None, str]] = set()
    for hit in hits:
        citation = DEFAULT_GROUNDED_ANSWER_ASSEMBLER.citation_from_hit(hit)
        key = (citation.resource_id, citation.locator, citation.quote)
        if key in seen:
            continue
        seen.add(key)
        citations.append(citation)
    return citations


def format_answer_for_history(response: RagQueryResponse) -> str:
    lines = [(response.grounded_answer.text if response.grounded_answer else "").strip()]
    if not lines[0]:
        lines[0] = ""
    evidence = _history_evidence_items(response)
    if evidence:
        lines.extend(["", "**Evidence**"])
        for index, item in enumerate(evidence[:8], start=1):
            title = _escape_markdown(item["title"])
            score = item.get("score")
            score_text = f" ({round(score * 100)}%)" if isinstance(score, (int, float)) else ""
            lines.append(f"{index}. {title}{score_text}")
    return "\n".join(lines).strip()


def _history_evidence_items(response: RagQueryResponse) -> list[dict[str, object]]:
    items: list[dict[str, object]] = []
    seen: set[str] = set()
    citations = response.grounded_answer.citations if response.grounded_answer else []
    for citation in citations:
        if citation.resource_id in seen:
            continue
        seen.add(citation.resource_id)
        hit = next(
            (
                candidate
                for candidate in response.hits
                if candidate.resource_id == citation.resource_id
            ),
            None,
        )
        items.append(
            {
                "title": hit.title if hit and hit.title else citation.resource_id,
                "score": hit.score if hit else None,
            }
        )
    if items:
        return items
    for hit in response.hits:
        if hit.resource_id in seen:
            continue
        seen.add(hit.resource_id)
        items.append({"title": hit.title or hit.resource_id, "score": hit.score})
    return items


def _escape_markdown(value: str) -> str:
    return value.replace("`", "\\`").replace("*", "\\*").replace("_", "\\_").replace("~", "\\~")


def _enqueue_upsert(db: Session, doc: QnaDocument) -> None:
    partition_id = assign_default_partition(
        db,
        target=doc,
        source_namespace="qna",
        candidate_scope_kind="company",
    )
    projection_event = record_projection_event(
        db,
        resource_type=QNA_DOCUMENT_RESOURCE_TYPE,
        resource_id=doc.id,
        retrieval_partition_id=partition_id,
        change_kind="content",
        desired_state="active",
        content_checksum=doc.content_checksum,
    )
    ensure_rag_source_adapters_registered()
    enqueue_rag_sync_job(
        db,
        scope_kind=RagScopeKind.COMPANY,
        workspace_id=None,
        resource_type=QNA_DOCUMENT_RESOURCE_TYPE,
        resource_id=doc.id,
        operation=RagSyncOperation.UPSERT,
        content_checksum=doc.content_checksum,
        projection_event=projection_event,
    )


