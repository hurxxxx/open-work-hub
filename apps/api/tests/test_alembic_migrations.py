@pytest.fixture
def alembic_config(
    monkeypatch: pytest.MonkeyPatch,
    postgres_dsn: str,
) -> Iterator[object]:
    monkeypatch.setenv("OPEN_ALM_POSTGRES_DSN", postgres_dsn)
    monkeypatch.setenv("OPEN_ALM_API_AUTO_MIGRATE", "0")
    monkeypatch.setenv("OPEN_ALM_LLM_HEALTHCHECK_ON_STARTUP", "0")

    from open_alm_api.core.db import _alembic_config
    from open_alm_api.core.settings import get_settings

    get_settings.cache_clear()
    engine = create_engine(postgres_dsn)
    with engine.begin() as connection:
        # ``postgres_dsn`` is already a fresh per-test database. Preserve the
        # pgvector extension installed by the native test harness; dropping
        # ``public`` here also drops extension-owned types and makes the
        # application migration depend on the unprivileged test role being
        # allowed to recreate a cluster extension.
        connection.exec_driver_sql("CREATE SCHEMA IF NOT EXISTS public")
    engine.dispose()

    try:
        yield _alembic_config()
    finally:
        get_settings.cache_clear()


def _assert_no_model_drift(alembic_config) -> None:
    try:
        command.check(alembic_config)
    except AutogenerateDiffsDetected as error:
        pytest.fail(
            "SQLAlchemy models and the Alembic head differ. Add or correct the "
            "migration before changing the application model. "
            f"Details: {error}"
        )


def _postgresql_index_metadata(connection, index_name: str):
    return (
        connection.execute(
            text(
                """
                SELECT indexes.indisunique,
                       indexes.indisvalid,
                       indexes.indisready,
                       pg_get_expr(indexes.indpred, indexes.indrelid) AS predicate
                FROM pg_catalog.pg_index AS indexes
                JOIN pg_catalog.pg_class AS index_class
                  ON index_class.oid = indexes.indexrelid
                JOIN pg_catalog.pg_namespace AS index_namespace
                  ON index_namespace.oid = index_class.relnamespace
                WHERE index_namespace.nspname = current_schema()
                  AND index_class.relname = :index_name
                """
            ),
            {"index_name": index_name},
        )
        .mappings()
        .one()
    )


