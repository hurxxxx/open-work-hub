import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = path.join(
  root,
  'packages/contracts/auth-realtime-contract.json',
);
const tsPath = path.join(
  root,
  'packages/contracts/src/auth-realtime.generated.ts',
);
const pyPath = path.join(
  root,
  'apps/api/src/open_work_hub_api/domains/auth/realtime_contract_generated.py',
);
const check = process.argv.includes('--check');

const source = JSON.parse(await readFile(sourcePath, 'utf8'));
const eventType = source?.accessChanged?.eventType;
const appAvailability = source?.accessChanged?.reasons?.appAvailability;
const workspaceMembership = source?.accessChanged?.reasons?.workspaceMembership;
for (const [label, value] of [
  ['accessChanged.eventType', eventType],
  ['accessChanged.reasons.appAvailability', appAvailability],
  ['accessChanged.reasons.workspaceMembership', workspaceMembership],
]) {
  if (typeof value !== 'string' || !value.trim()) {
    throw new Error(`Invalid auth realtime contract value: ${label}`);
  }
}

const banner =
  'Generated by scripts/generate-auth-realtime-contract.mjs. Do not edit.';
const ts = `// ${banner}\n\nexport const AUTH_REALTIME_EVENT_TYPES = {\n  accessChanged: ${JSON.stringify(eventType)},\n} as const;\n\nexport const AUTH_ACCESS_CHANGE_REASONS = {\n  appAvailability: ${JSON.stringify(appAvailability)},\n  workspaceMembership: ${JSON.stringify(workspaceMembership)},\n} as const;\n`;
const py = `# ${banner}\n\nfrom typing import Final\n\nAUTH_ACCESS_CHANGED: Final = ${JSON.stringify(eventType)}\nAUTH_ACCESS_CHANGED_REASON_APP_AVAILABILITY: Final = ${JSON.stringify(appAvailability)}\nAUTH_ACCESS_CHANGED_REASON_WORKSPACE_MEMBERSHIP: Final = ${JSON.stringify(workspaceMembership)}\n`;

async function update(target, expected) {
  if (check) {
    let actual = '';
    try {
      actual = await readFile(target, 'utf8');
    } catch {
      throw new Error(
        `Missing generated auth realtime contract: ${path.relative(root, target)}`,
      );
    }
    if (actual !== expected) {
      throw new Error(
        `Generated auth realtime contract is stale: ${path.relative(root, target)}`,
      );
    }
    return;
  }
  await writeFile(target, expected);
}

await update(tsPath, ts);
await update(pyPath, py);
