import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

import { validateAppContracts } from './app-contract-validation.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = path.join(root, 'packages/contracts/app-contracts.json');
const schemaPath = path.join(
  root,
  'packages/contracts/app-contracts.schema.json',
);
const tsPath = path.join(
  root,
  'packages/contracts/src/app-contracts.generated.ts',
);
const pyPath = path.join(
  root,
  'apps/api/src/open_work_hub_api/core/app_contracts_generated.py',
);
const check = process.argv.includes('--check');

const sourceText = await readFile(sourcePath, 'utf8');
const source = JSON.parse(sourceText);
const schema = JSON.parse(await readFile(schemaPath, 'utf8'));
validateAppContracts(source, schema);
const apps = source.apps;

const canonical = `${JSON.stringify(source)}\n`;
const revision = `sha256:${createHash('sha256').update(canonical).digest('hex')}`;
const banner =
  'Generated by scripts/generate-app-contracts.mjs. Do not edit.\n';
const json = JSON.stringify(apps, null, 2);
const ts = `// ${banner}\nexport const APP_CONTRACT_REVISION = ${JSON.stringify(revision)} as const;\nexport const APP_CONTRACTS = ${json} as const;\n\nexport type AppContract = (typeof APP_CONTRACTS)[number];\nexport type AppId = AppContract['app_id'];\nexport type AppRouteContract = AppContract['routes'][number];\nexport type AppRouteId = AppRouteContract['route_id'];\nexport type AppExecutionContextKind = AppContract['execution_context_kind'];\nexport type AppResourceScope = AppContract['resource_scope'];\n\nexport const APP_CONTRACT_BY_ID = new Map<AppId, AppContract>(\n  APP_CONTRACTS.map((app) => [app.app_id, app]),\n);\n\nexport const APP_ROUTE_BY_ID = new Map<AppRouteId, AppRouteContract & { app_id: AppId; route_base: string }>(\n  APP_CONTRACTS.flatMap((app) =>\n    app.routes.map((route) => [route.route_id, { ...route, app_id: app.app_id, route_base: app.route_base }] as const),\n  ),\n);\n`;

const pyApps = JSON.stringify(apps, null, 2)
  .replaceAll('true', 'True')
  .replaceAll('false', 'False')
  .replaceAll('null', 'None');
const py = `# ${banner}\nfrom __future__ import annotations\n\nfrom typing import Final\n\nAPP_CONTRACT_REVISION: Final = ${JSON.stringify(revision)}\nAPP_CONTRACTS: Final = ${pyApps}\nAPP_CONTRACT_BY_ID: Final = {app["app_id"]: app for app in APP_CONTRACTS}\nAPP_ROUTE_BY_ID: Final = {\n    route["route_id"]: {**route, "app_id": app["app_id"], "route_base": app["route_base"]}\n    for app in APP_CONTRACTS\n    for route in app["routes"]\n}\n`;

async function update(target, expected) {
  if (check) {
    let actual = '';
    try {
      actual = await readFile(target, 'utf8');
    } catch {
      throw new Error(
        `Missing generated app contract: ${path.relative(root, target)}`,
      );
    }
    if (actual !== expected) {
      throw new Error(
        `Generated app contract is stale: ${path.relative(root, target)}`,
      );
    }
    return;
  }
  await writeFile(target, expected);
}

await update(tsPath, ts);
await update(pyPath, py);
